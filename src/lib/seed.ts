/**
 * 内置文案的内容指纹。
 *
 * 用一个短哈希而不是全文对比：存全文会让 data/prompts.json 膨胀一倍，
 * 而这里只需要回答「和当前种子一不一样」。用 FNV-1a —— 手写几行就够，
 * 不为这点事引第三方依赖。
 */
export function seedHashOf(system: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < system.length; i++) {
    h ^= system.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16);
}

